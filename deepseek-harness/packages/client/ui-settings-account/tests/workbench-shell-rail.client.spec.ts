import { describe, expect, it } from 'vitest'
import { readFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'
import {
  defaultRecordRail,
  recordRailSignature,
  shouldShowRecordRail,
} from '../src/client/DigitalHumanRecordRail.tsx'

const root = dirname(fileURLToPath(import.meta.url))
const panel = readFileSync(join(root, '../src/client/DigitalHumanPanel.tsx'), 'utf8')
const panelCss = readFileSync(join(root, '../src/client/DigitalHumanPanel.module.css'), 'utf8')
const packs = readFileSync(join(root, '../src/client/DigitalHumanPublishPacks.tsx'), 'utf8')
const calendar = readFileSync(join(root, '../src/client/DigitalHumanCalendar.tsx'), 'utf8')
const accounts = readFileSync(join(root, '../src/client/DigitalHumanPlatformAccounts.tsx'), 'utf8')
const download = readFileSync(join(root, '../src/client/DigitalHumanVideoDownload.tsx'), 'utf8')

describe('record rail visibility and defaults', () => {
  it('shows the 300px rail on company inner pages but not home or the company list', () => {
    expect(shouldShowRecordRail('home', false)).toBe(false)
    expect(shouldShowRecordRail('home', true)).toBe(false)
    expect(shouldShowRecordRail('companies', false)).toBe(false)
    expect(shouldShowRecordRail('companies', true)).toBe(true)
    expect(shouldShowRecordRail('create', false)).toBe(true)
    expect(shouldShowRecordRail('works', false)).toBe(true)
    expect(shouldShowRecordRail('materials', false)).toBe(true)
    expect(shouldShowRecordRail('calendar', false)).toBe(true)
    expect(shouldShowRecordRail('platform-accounts', false)).toBe(true)
    expect(shouldShowRecordRail('publish-packs', false)).toBe(true)
    expect(shouldShowRecordRail('publish', false, false)).toBe(false)
    expect(shouldShowRecordRail('publish', false, true)).toBe(true)
    expect(shouldShowRecordRail('video-download', false, false)).toBe(false)
    expect(shouldShowRecordRail('video-download', false, true)).toBe(true)
    expect(shouldShowRecordRail('industry-hotboard', false, false)).toBe(false)
    expect(shouldShowRecordRail('industry-hotboard', false, true)).toBe(true)
    expect(defaultRecordRail('industry-hotboard', false)).toEqual({ title: '热榜', empty: '还没有行业热榜。' })
    expect(defaultRecordRail('calendar', false)).toEqual({ title: '这天排期', empty: '这一天没有排期' })
    expect(defaultRecordRail('platform-accounts', false)).toEqual({ title: '账号', empty: '还没有账号' })
    expect(defaultRecordRail('publish-packs', false)).toEqual({ title: '发布包', empty: '还没有发布包' })
    expect(defaultRecordRail('companies', true)?.empty).toBe('这家还没有成片。')
    expect(defaultRecordRail('home', false)).toBe(null)
  })

  it('signatures ignore callback identity so registry updates do not loop', () => {
    const a = { title: '任务', empty: '还没有任务。', items: [{ id: '1', title: 'A', onClick: () => 1 }] }
    const b = { title: '任务', empty: '还没有任务。', items: [{ id: '1', title: 'A', onClick: () => 2 }] }
    expect(recordRailSignature(a)).toBe(recordRailSignature(b))
    expect(recordRailSignature({ ...a, items: [{ id: '1', title: 'B', onClick: () => 1 }] })).not.toBe(recordRailSignature(a))
  })
})

